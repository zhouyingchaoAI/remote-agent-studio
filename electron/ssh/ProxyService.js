/**
 * ProxyService - 远程网络代理自动配置
 *
 * 两种模式:
 *  1. tunnel  - SSH 反向隧道:远程 127.0.0.1:<remotePort> -> 本机可达的代理(如本机 Clash 7890)。
 *               远程无法直连外网时,借道本机/局域网代理访问 OpenAI/Anthropic。
 *  2. direct  - 直接把局域网内已有代理地址写入远程环境变量(远程能直连该代理时用)。
 *
 * 配置写入远程 ~/.remote-agent-proxy.sh,并注入每次 agent 命令的环境。
 */
const PROXY_FILE = '~/.remote-agent-proxy.sh';

class ProxyService {
  constructor(ssh) {
    this.ssh = ssh;
    this.current = null; // {mode, proxyUrl, remotePort}
  }

  /**
   * cfg: { mode: 'tunnel'|'direct'|'none',
   *        localProxyHost, localProxyPort,   // tunnel 模式:本机侧代理
   *        remotePort,                        // tunnel 模式:远程监听端口(默认 18080)
   *        directProxyUrl }                   // direct 模式:如 http://192.168.1.10:7890
   */
  async configure(cfg, log = () => {}) {
    // 清理旧隧道
    if (this.current?.mode === 'tunnel' && this.current.remotePort) {
      await this.ssh.stopReverseTunnel(this.current.remotePort).catch(() => {});
    }

    if (!cfg || cfg.mode === 'none') {
      await this.ssh.exec(`rm -f ${PROXY_FILE}`);
      this.current = null;
      log('已清除远程代理配置\n');
      return { ok: true, proxyUrl: null };
    }

    let proxyUrl;
    if (cfg.mode === 'tunnel') {
      let remotePort = cfg.remotePort || 18080;
      const host = cfg.localProxyHost || '127.0.0.1';
      const port = cfg.localProxyPort || 7890;
      // 端口被占用时自动向后尝试 10 个端口
      let bound = false, lastErr = null;
      for (let i = 0; i < 10 && !bound; i++) {
        try {
          log(`建立反向隧道: 远程127.0.0.1:${remotePort} -> 本机侧 ${host}:${port} ...\n`);
          await this.ssh.startReverseTunnel(remotePort, host, port);
          bound = true;
        } catch (e) {
          lastErr = e;
          log(`端口 ${remotePort} 不可用(${e.message}),尝试 ${remotePort + 1} ...\n`);
          remotePort++;
        }
      }
      if (!bound) throw lastErr;
      proxyUrl = `http://127.0.0.1:${remotePort}`;
      this.current = { mode: 'tunnel', proxyUrl, remotePort };
    } else {
      proxyUrl = cfg.directProxyUrl;
      if (!proxyUrl) throw new Error('direct 模式需要提供代理地址');
      this.current = { mode: 'direct', proxyUrl };
    }

    // 校验代理地址格式,并加引号写入,防止特殊字符破坏脚本
    if (!/^https?:\/\/[A-Za-z0-9_.\-]+(:\d+)?\/?$/.test(proxyUrl)) {
      throw new Error(`代理地址格式不合法: ${proxyUrl}`);
    }
    const script = [
      '# Generated by Remote Agent Studio',
      `export HTTP_PROXY='${proxyUrl}'`,
      `export HTTPS_PROXY='${proxyUrl}'`,
      `export http_proxy='${proxyUrl}'`,
      `export https_proxy='${proxyUrl}'`,
      `export ALL_PROXY='${proxyUrl}'`,
      'export NO_PROXY=localhost,127.0.0.1'
    ].join('\n');
    await this.ssh.exec(`cat > ${PROXY_FILE} <<'EOF'\n${script}\nEOF`);
    log(`代理环境已写入 ${PROXY_FILE}: ${proxyUrl}\n`);

    // 连通性检测:多次采样。单次成功掩盖不了间歇性故障,
    // 而长任务恰恰死于「偶尔一次 CONNECT 503」——必须把波动暴露出来
    log('检测代理连通性(连续 5 次采样,看稳定性)...\n');
    const probe = await this.ssh.exec(
      `. ${PROXY_FILE}; for i in 1 2 3 4 5; do `
      + `curl -sS -o /dev/null -m 12 -w '%{http_code} ' https://api.anthropic.com 2>&1 | tail -c 24; `
      + `done`
    );
    const raw = String(probe.stdout || '').trim();
    const codes = raw.split(/\s+/).filter(Boolean);
    const good = codes.filter((c) => /^[0-9]{3}$/.test(c) && c !== '000');
    const ok = good.length > 0;
    const rate = codes.length ? Math.round((good.length / codes.length) * 100) : 0;

    if (ok && good.length === codes.length) {
      log(`代理连通 ✓ 5/5 成功 (HTTP ${good[0]})\n`);
    } else if (ok) {
      log(`⚠️ 代理不稳定:${good.length}/${codes.length} 成功(${rate}%),返回 ${codes.join(' ')}\n`
        + '  长任务会因偶发失败中断(表现为 Reconnecting / CONNECT 503)。\n'
        + '  建议:换一个更稳定的代理节点,或在 Clash 里为 api.anthropic.com / api.openai.com 指定固定节点。\n');
    } else {
      log(`代理检测未通过: ${raw || probe.stderr}\n`);
    }
    return { ok, proxyUrl, successRate: rate, codes };
  }

  /** 供 agent/安装命令使用的环境前缀 */
  envPrefix() {
    return `[ -f ${PROXY_FILE} ] && . ${PROXY_FILE};`;
  }
}

module.exports = { ProxyService, PROXY_FILE };
